def haversine_m(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Great-circle distance in metres between two WGS-84 coordinates."""
    lat1, lon1, lat2, lon2 = map(math.radians, [lat1, lon1, lat2, lon2])
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = math.sin(dlat / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin(dlon / 2) ** 2
    return EARTH_RADIUS_M * 2 * math.asin(math.sqrt(a))


def match_to_corridor(
    lat: float,
    lng: float,
    direction: str,
) -> Tuple[float, float, float]:
    """
    Snap (lat, lng) to the nearest point on the jeepney corridor polyline.

    Implements nearest-point-on-segment with Haversine distance, ported from
    StopZoneMap.jsx::snapToRoad().  Iterates every segment of the polyline and
    projects the query point onto it, clamping t ∈ [0, 1] so the projection
    stays within the segment.

    Parameters
    ----------
    lat, lng  : WGS-84 coordinates to snap
    direction : "MALANDAY-RECTO" → MR_CORRIDOR; anything else → RM_CORRIDOR

    Returns
    -------
    (snapped_lat, snapped_lng, snap_distance_m)
    """
    corridor  = MR_CORRIDOR if direction == "MALANDAY-RECTO" else RM_CORRIDOR
    best_lat  = lat
    best_lng  = lng
    best_dist = math.inf

    for i in range(len(corridor) - 1):
        ax, ay = corridor[i]
        bx, by = corridor[i + 1]
        dx = bx - ax
        dy = by - ay
        denom = dx * dx + dy * dy
        if denom == 0.0:
            t = 0.0
        else:
            t = max(0.0, min(1.0, ((lat - ax) * dx + (lng - ay) * dy) / denom))
        s_lat = ax + t * dx
        s_lng = ay + t * dy
        d = haversine_m(lat, lng, s_lat, s_lng)
        if d < best_dist:
            best_dist = d
            best_lat  = s_lat
            best_lng  = s_lng

    return best_lat, best_lng, best_dist
